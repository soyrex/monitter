import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync('src/lib/project-ideas.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { editIdeaDraft, ideaSaveList, parseIdeaTags } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const project = { ideasRevision: 3, ideas: [{ id: 'a', title: 'Original', markdown: 'Details', createdAt: 1, updatedAt: 2, history: [], tags: ['old'], authorKind: 'agent' }] };
const draft = editIdeaDraft(project, project.ideas[0]);
const reactiveDraft = editIdeaDraft(project, new Proxy(project.ideas[0], {}));
reactiveDraft.idea.tags.push('reactive-only');
assert.deepEqual(project.ideas[0].tags, ['old']);
draft.idea.title = '  Revised  ';
draft.idea.tags.push('new');
assert.equal(project.ideas[0].title, 'Original');
assert.deepEqual(project.ideas[0].tags, ['old']);
assert.equal(ideaSaveList(project, draft)[0].title, 'Revised');
assert.equal(ideaSaveList(project, draft)[0].authorKind, 'agent');
assert.throws(() => ideaSaveList({ ...project, ideasRevision: 4 }, draft), /draft is retained/);
assert.equal(draft.idea.title, '  Revised  ');
assert.deepEqual(parseIdeaTags(' one, two, one, '), ['one', 'two']);
assert.throws(() => parseIdeaTags('x'.repeat(33)), /16 tags/);
draft.idea.markdown = '😀'.repeat(32769);
assert.throws(() => ideaSaveList(project, draft), /128 KiB/);
console.log('Idea draft isolation, revision conflict, metadata and size checks passed.');
