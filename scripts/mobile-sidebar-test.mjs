import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(readFileSync('scripts/ui-fixture.js', 'utf8'));
try {
  await page.goto(process.env.MONITTER_TEST_URL || 'http://127.0.0.1:18435/');
  const shell = page.locator('.app-shell').first();
  await expect(shell).toHaveClass(/mobile-navigation/, { timeout: 60000 });
  await expect(page.getByRole('complementary', { name: 'Agents and tasks' })).toBeVisible();
  await expect(page.locator('.pane-grid').first()).toBeHidden();
  await expect(page.locator('.pane-grid').first()).toHaveAttribute('inert', '');
  const duration = await page.locator('.pane-grid').first().evaluate(node => getComputedStyle(node).transitionDuration);
  expect(duration).toContain('0.24s');
  await page.getByRole('button', { name: 'New chat with Atlas', exact: true }).click();
  await expect(page.locator('[data-tab-kind="draft"]')).toHaveCount(1);
  await expect(page.locator('.tab-picker-trigger')).toBeVisible();
  await expect(page.getByRole('complementary', { name: 'Agents and tasks' })).toBeHidden();
  await page.getByRole('button', { name: 'Back to chats' }).click();
  await expect(page.getByRole('complementary', { name: 'Agents and tasks' })).toBeVisible();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(page.locator('.pane-grid').first()).toHaveCSS('transition-duration', '0s');
  await page.getByRole('button', { name: 'Preferences', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Back to chats' })).toBeVisible();
  await page.setViewportSize({ width: 1200, height: 900 });
  await expect(shell).not.toHaveClass(/sidebar-collapsed/);
  const resize = page.getByRole('separator', { name: 'Resize main sidebar' });
  await resize.focus();
  await page.keyboard.press('Enter');
  await expect(shell).toHaveClass(/sidebar-collapsed/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.setViewportSize({ width: 1200, height: 900 });
  await expect(shell).toHaveClass(/sidebar-collapsed/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(shell).toHaveClass(/mobile-navigation/);
  await expect(page.getByRole('complementary', { name: 'Agents and tasks' })).toBeVisible();
  expect(errors).toEqual([]);
  console.log('Mobile two-screen navigation, back button, desktop preference and reload checks passed.');
} finally { await browser.close(); }
