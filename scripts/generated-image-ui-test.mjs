import { webkit, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const browser=await webkit.launch();
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
await page.addInitScript(readFileSync('scripts/ui-fixture.js','utf8')+`
  const state=window.__MONITTER_QA__.snapshot();
  state.tasks=[{id:'image-chat',agentId:'atlas',title:'Screenshot reply',status:'completed',archived:false,parentTaskId:null,channelId:null,projectId:null,hostId:'local',cwd:'/tmp/monitter-ui-test',provider:'codex',model:'',sandbox:'read-only',nativeSessionId:null,createdAt:1,updatedAt:1}];
  state.messages=[{id:'image-reply',taskId:'image-chat',role:'assistant',text:'Screenshot attached.',createdAt:2,attachments:[{id:'screenshot',name:'Generated image.png',mimeType:'image/png',size:68,path:'Generated by Codex',previewDataUrl:'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1sAAAAASUVORK5CYII='}]}];
  window.__MONITTER_QA__.setSnapshot(state);
`);
try {
  await page.goto(process.env.MONITTER_TEST_URL || 'http://127.0.0.1:18442/');
  await page.locator('[data-task-id="image-chat"] .task-select').click({timeout:60000});
  const image=page.locator('article.message .attachment img');
  await expect(image).toBeVisible();
  await expect.poll(()=>image.evaluate(node=>node.complete && node.naturalWidth>0)).toBe(true);
  const bounds=await image.boundingBox();
  expect(bounds.width).toBeGreaterThan(100);
  expect(bounds.x+bounds.width).toBeLessThanOrEqual(390);
  console.log('Generated screenshot displays inline within the mobile chat width.');
} finally {await browser.close();}
