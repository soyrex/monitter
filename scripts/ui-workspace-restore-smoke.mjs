import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';

const url = process.env.MONITTER_TEST_URL || 'http://127.0.0.1:18433';
mkdirSync('verification', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const passed = [], errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.addInitScript({ content: readFileSync('scripts/ui-fixture.js', 'utf8') + `
    const qa = window.__MONITTER_QA__, snapshot = qa.snapshot(), now = Date.now();
    for (const id of ['restore-a', 'restore-b']) snapshot.tasks.push({ id, agentId:'atlas', title:id, nativeSessionId:null, status:'idle', archived:false, createdAt:now, updatedAt:now, parentTaskId:null, channelId:null, projectId:null, hostId:'local', cwd:'/tmp/monitter-ui-test', provider:'codex', model:'', sandbox:'read-only' });
    qa.setSnapshot(snapshot);
  ` });
  await page.goto(url);
  const main = page.locator('.pane-leaf[data-pane-id="main"]');
  const open = name => page.locator('.sidebar .task-select').filter({ hasText:name }).click();
  await open('restore-a');
  await main.getByLabel('Task message', { exact:true }).fill('draft A survives reload');
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+p' : 'Control+p');
  await page.getByRole('dialog', { name:'Controls', exact:true }).getByText('Two columns', { exact:true }).click();
  const second = page.locator('.pane-leaf').last();
  await second.click({ position:{ x:100, y:100 } });
  await open('restore-b');
  await second.getByLabel('Task message', { exact:true }).fill('draft B survives reload');
  const divider = page.getByRole('separator', { name:'Resize panes' }).first();
  await divider.focus();
  await divider.press((await divider.getAttribute('aria-orientation')) === 'vertical' ? 'ArrowRight' : 'ArrowDown');
  await page.getByRole('separator', { name:'Resize main sidebar', exact:true }).press('Enter');
  await page.waitForTimeout(20);
  await page.reload();
  await expect(page.locator('.pane-leaf')).toHaveCount(2);
  await expect(main.getByLabel('Task message', { exact:true })).toHaveValue('draft A survives reload');
  const restoredSecond = page.locator('.pane-leaf').last();
  await expect(restoredSecond.getByLabel('Task message', { exact:true })).toHaveValue('draft B survives reload');
  await expect(page.getByRole('separator', { name:'Resize main sidebar', exact:true })).toHaveAttribute('aria-valuetext', /Collapsed/);
  await expect(page.getByRole('separator', { name:'Resize panes' }).first()).toHaveAttribute('aria-valuenow', '55');
  passed.push('reload restores pane layout ratio, selected pane tabs, drafts, and sidebar state');
  await restoredSecond.click({ position:{ x:100, y:100 } });
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+w' : 'Control+w');
  await expect(restoredSecond.getByRole('button', { name:'restore-b', exact:true })).toHaveCount(0);
  await expect(page.locator('.pane-leaf')).toHaveCount(2);
  await expect(main.getByRole('button', { name:'restore-a', exact:true })).toBeVisible();
  passed.push('Cmd/Ctrl-W closes only the selected tab in the active pane');
  await restoredSecond.getByRole('button', {name:'Open terminal',exact:true}).click();
  await expect(restoredSecond.locator('.terminal-pane .xterm-helper-textarea')).toBeAttached({timeout:30000});
  const oldTerminal = await page.evaluate(() => window.__MONITTER_QA__.terminals()[0]);
  await page.reload();
  await expect(page.locator('.terminal-tab')).toHaveCount(1);
  const freshTerminal = await page.evaluate(() => window.__MONITTER_QA__.terminals()[0]);
  expect(freshTerminal.id).not.toBe(oldTerminal.id);
  expect(freshTerminal.cwd).toBe(oldTerminal.cwd);
  expect(freshTerminal.hostId).toBe(oldTerminal.hostId);
  await expect(page.locator('.terminal-pane .xterm-helper-textarea')).toBeAttached({timeout:30000});
  await page.locator('.terminal-pane .xterm-helper-textarea').focus();
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+w' : 'Control+w');
  await expect(page.locator('.terminal-tab')).toHaveCount(0);
  await expect(page.locator('.pane-leaf')).toHaveCount(2);
  passed.push('restores fresh terminal in saved host/folder and Cmd-W closes only its tab');
  expect(await page.evaluate(() => window.__MONITTER_QA__.calls.filter(call => ['createTask','sendMessage','sendChannelMessage'].includes(call.method)))).toHaveLength(0);
  passed.push('workspace restoration starts no agent turns');
  if (errors.length) throw Error(errors.join('\n'));
  writeFileSync('verification/ui-workspace-restore-results.json', JSON.stringify({ passed, errors }, null, 2));
  console.log(JSON.stringify({ passed, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path:'verification/ui-workspace-restore-failure.png' });
  writeFileSync('verification/ui-workspace-restore-results.json', JSON.stringify({ passed, errors, error:String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
